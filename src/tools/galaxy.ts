function quorumOriginalPassed(risks: readonly string[]): number | undefined {
  for (const r of risks) {
    const m = /^quorum: group .* not reached ? (\d+)\/\d+ passed/.exec(r)
    if (m) return Number(m[1])
  }
  return undefined
}

